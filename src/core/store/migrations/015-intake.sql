-- ═══════════════════════════════════════════════════════════════
-- 015 — 통(通): 파일이 척추다. **넣은 파일은 전부 한 줄, 무엇이 됐는지까지**
-- ═══════════════════════════════════════════════════════════════
--
-- [ADR-023](docs/ADR-023-통-묶음-자격-입구순서.md) 결정 1 · [대기목록 8].
-- 2026-08-21에 확인 질문 4개에 답을 받아 「제안」에서 「결정」으로 올라갔다.
--
-- 사용자가 겪은 것: **13MB 단가표를 넣었는데 「가져오기 기록」에 한 줄도 없었다.**
-- 넣은 사람은 그것을 실패로 읽는다.
--
-- ─────────────────────────────────────────────────────────────
-- ★★ 새 장부를 만들지 않는다 — 통은 `file_sighting`이다 ★★
--
-- ADR-023과 대기목록 8은 「장부는 파일이어야 한다」를 **아직 없는 것**처럼 적었다.
-- **이미 있었다.** 009가 정확히 그 척추를 세웠고, 앵커의 뜻까지 같은 말로 적어 뒀다:
--
--     예전 사고방식   적재됐다 → 기록이 남는다
--     009            **봤다 → 기록이 남는다** → (적재되면) 배치가 붙는다
--
-- 그래서 여기서 `file_intake` 같은 표를 새로 파지 않는다. 파면 장부가 둘이 되고,
-- **같은 일을 하는 자리가 둘이면 어느 쪽이 참인지 모른다**(U-3). 009를 통으로
-- 승격시키고, 빠져 있던 두 가지만 채운다.
--
-- ★ 실측이 가리킨 빠진 자리 (2026-08-21 · 이 기기 · `.tmp/pnl.sqlite` · `public/demo.sqlite`) ★
--
--   file_sighting 실 DB 4행 · 데모 3행 — **전부 batch가 붙은 Fact 파일이다**
--   원가 파일(`2026-01 통합 매출 대시보드.xlsx`)은 데모에서 `cost_history` 35행과
--   `pending_cost` 171행을 만들었는데 **`file_sighting`에 한 줄도 없다**
--     → `run-reference.ts`가 `recordFileSighting`을 부르지 않는다 (코드 쪽에서 고친다)
--   `pending_cost`는 `source_hash`·`source_name`을 **이미 들고 있다** (011)
--   `cost_history`는 출처 컬럼이 **하나도 없다** — 어느 파일에서 왔는지 영영 모른다
--
-- ─────────────────────────────────────────────────────────────
-- ★ 왜 「깊은 층」(파싱된 표 전 행)이 여기 없나 ★
--
-- ADR-023이 통을 두 깊이로 나눴고(얕게=장부 · 깊게=표 보관), 사용자는 깊은 층을
-- **「파싱된 표 전 행」**으로 확인해 줬다. 그런데 같은 ADR의 재검토 트리거가
-- 「**보관 비용이 실측으로 감당 안 되면 깊은 층만 미루고 얕은 층만 간다**」이다.
--
-- 광고 파일 하나가 **80,137행 × 43열**이다. 저장 형태(행당 JSON인가 셀당 행인가)를
-- 재보지 않고 정하면 그 선택이 스키마에 굳는다. **재고 나서 016으로 간다.**
-- 얕은 층만으로도 사용자가 겪은 그 일(「원가 파일이 기록에 없다」)은 닫힌다.
-- ─────────────────────────────────────────────────────────────
--
-- ★ Fact가 아니라 메타다 ★
-- 009와 같다 — 공통 6컬럼(LOCK 1)이 없고 `row_shadow` 트리거도 안 붙는다.
-- 되돌리기의 대상도 아니다. batch가 사라져도 「이 파일을 봤고 이런 것이 됐다」는
-- 남는다(009의 `ON DELETE SET NULL`과 같은 판단).
--
-- 001을 고치지 않는다 (스키마 LOCK). 새 번호로 쌓는다.

-- ───────────────────────────────────────────────────────────────
-- 1. 이 파일이 **무엇이 됐나**
-- ───────────────────────────────────────────────────────────────
--
-- 한 목격이 여러 결과를 낸다. 원가 파일 하나가 `cost_history`에 35건을 넣고
-- `pending_cost`에 171건을 남기고 SKU를 새로 만든다 — 그 셋은 **다른 사건**이라
-- 한 칸에 못 담는다. 그래서 결과마다 한 줄이다.
--
-- ★ `kind`에 CHECK를 걸지 않는다 — 008·009가 세운 규칙 그대로 ★
-- 목록은 TypeScript가 닫는다(`OutcomeKind`). SQLite는 CHECK를 ALTER로 못 바꿔서
-- 여기 굳히면 종류 하나 더할 때마다 테이블을 다시 짓는다.
--
-- ★ 왜 `count`뿐이고 대상 id가 없나 ★
-- 「원가 35건이 들어갔다」는 말에 필요한 것은 수다. 어느 `cost_history.id`인지는
-- **되돌리기가 생길 때** 필요한데, 기준 데이터의 되돌리기는 아직 결정이 아니다
-- (`row_shadow`가 Fact 5종만 덮는다 — 002). 없는 기능의 자리를 미리 파지 않는다.
--
-- 규칙: 이 표는 **batch가 못 담는 결과만** 담는다.
--
-- Fact 적재의 결과는 `batch`가 이미 갖고 있다 — 표별 행 수(007 load breakdown) ·
-- 되돌리기 단위 · 지문. 그것을 여기 복사하면 같은 수가 두 곳에 살고, 둘이 갈리는
-- 날 어느 쪽이 참인지 모른다 (U-3의 데이터판).
--
--     Fact 파일   file_sighting.batch_id  ->  batch (007)
--     기준 파일   sighting_outcome            batch가 없다. 그래서 이 표가 생겼다
--
-- 그래서 통에서 Fact 파일의 결과 줄이 비어 있는 것은 결손이 아니다. 화면이
-- 「무엇이 됐나」를 물을 때 둘을 함께 읽는다. 다음 사람이 「Fact도 여기 넣자」로
-- 채우려 들면 그때 이 문단을 본다.
CREATE TABLE sighting_outcome (
  id           INTEGER PRIMARY KEY AUTOINCREMENT,
  sighting_id  INTEGER NOT NULL REFERENCES file_sighting(id) ON DELETE CASCADE,
  -- 무엇이 됐나. `cost` · `pending_cost` · `sku` · `listing` · `rows` · `skipped` …
  -- 목록은 코드가 닫는다.
  kind         TEXT NOT NULL,
  -- 몇 건인가. **0도 사실이다** — 「0건 들어갔다」와 「안 해 봤다」는 다르다 (§22).
  count        INTEGER NOT NULL,
  at           TEXT NOT NULL,
  -- 같은 목격에 같은 종류가 두 줄이면 화면이 두 번 말한다.
  -- ★ 재가져오기는 **갈아치우기**다 ★ 종류별 갱신으로 두면 1회차의 `cost 35`가
  -- 남은 채 2회차의 `cost_skipped 35`가 더해져 **두 실행을 섞어 말한다**(시험이 잡았다).
  -- 「무엇이 됐나」는 지금 상태에 대한 질문이라 `recordOutcomes`가 지우고 다시 넣는다.
  -- 이 UNIQUE는 그래도 남긴다 — 부르는 쪽이 같은 종류를 두 번 넘기는 실수를 문다.
  UNIQUE (sighting_id, kind)
) STRICT;

CREATE INDEX idx_sighting_outcome ON sighting_outcome(sighting_id);

-- ───────────────────────────────────────────────────────────────
-- 2. 원가 행이 **어느 파일에서 왔나**
-- ───────────────────────────────────────────────────────────────
--
-- `pending_cost`는 011부터 `source_hash`·`source_name`을 들고 있는데 `cost_history`는
-- 없다. 그래서 대기실을 거쳐 확정된 원가는 출처를 아는데, **파일에서 곧장 들어간
-- 원가는 출처를 모른다.** 같은 화면에 나란히 설 두 값이 한쪽만 계보를 갖는다.
--
-- ★ NULL이 정상값이다 ★ 사람이 손으로 넣은 원가에는 파일이 없다. 그 구분은 이미
-- `entered_by IN ('user','import')`가 하고 있고, 이 컬럼은 `import`인 행에만 찬다.
-- 「비어 있다」를 「출처 불명」으로 읽지 않는다 — `entered_by`를 함께 봐야 한다.
--
-- 표기는 `batch.source_hash`·`file_sighting.source_hash`와 같다 (SHA-1 hex).
-- FK를 걸지 않는 이유는 009와 같다: 목격은 시트 단위(`sheet_index` 포함 유일)라
-- 해시 하나가 여러 목격 행을 가리킬 수 있다. 조인은 해시로 한다.
ALTER TABLE cost_history ADD COLUMN source_hash TEXT;

-- 「이 파일이 넣은 원가」를 되짚는 경로.
CREATE INDEX idx_cost_history_source ON cost_history(source_hash);

