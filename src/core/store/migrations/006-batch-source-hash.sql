-- ═══════════════════════════════════════════════════════════════
-- 006 — batch의 파일 지문 컬럼 이름을 사실에 맞춘다
-- ═══════════════════════════════════════════════════════════════
--
-- 001이 `source_sha256`을 선언했지만 **한 번도 쓰이지 않았다** — `openBatch`에
-- 배관만 있고 값을 넘기는 호출부가 0곳이다.
--
-- 이제 쓸 자리가 생겼다: **같은 바이트·다른 이름** 판정. 7월 파일을 이름만 바꿔
-- 다시 넣으면 `source_key`가 갈라져 매출이 두 번 쌓인다(제트 매출은 파일명이
-- 키에 들어간다 — ADR-006 증축). 파일 지문을 배치에 남겨 두면 확인 단계에서
-- «이 파일은 이미 들어왔습니다»라고 말할 수 있다.
--
-- ★ 그런데 우리가 계산하는 것은 SHA-1이다 ★
-- `sha1.ts`가 이 앱의 유일한 해시이고(웹뷰에 `node:crypto`가 없어 순수 JS로 구현),
-- 지문 용도에는 SHA-1이 맞는 크기다 — 보안 경계가 아니라 «같은 파일인가»를 묻는다.
--
-- **SHA-1을 `source_sha256`이라는 칸에 넣는 것은 조용한 거짓말이다.** 컬럼이 아직
-- 비어 있는 지금이 이름을 고칠 가장 싼 순간이라, 값을 바꾸는 대신 이름을 고친다.
--
-- 001을 고치지 않는다 (스키마 LOCK). 새 번호로 쌓는다.
--
-- `batch`에는 그림자 트리거가 없다 — `row_shadow`는 Fact 5종만 덮는다
-- (`002-row-shadow.sql`). 그래서 이 이름 변경은 트리거를 건드리지 않는다.

ALTER TABLE batch RENAME COLUMN source_sha256 TO source_hash;

-- 같은 지문을 빠르게 찾기 위한 인덱스. 라이브러리 안에서만 묻는다.
CREATE INDEX IF NOT EXISTS idx_batch_source_hash ON batch(library_id, source_hash);

-- 적용 기록. 이 줄을 빠뜨리면 schema.test.ts의 '파일 수만큼 적용된다'가 잡는다.
INSERT INTO schema_migration (version, applied_at) VALUES (6, datetime('now'));
