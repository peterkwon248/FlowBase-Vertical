-- ═══════════════════════════════════════════════════════════════
-- 012 — 알림 확인: 「봤다」를 남기되 사실은 계속 센다
-- ═══════════════════════════════════════════════════════════════
--
-- ★ 왜 (2026-08-21, 사용자 지적) ★
--
-- 대시보드의 「파일에서 7행이 제외됐습니다」 배너가 **매번 뜬다.** 사용자의 말이
-- 그대로다: *"이게 계속 떠서 불편함. 한 번 확인하고 접거나 이런 버튼이 있어야 할 듯."*
--
-- 그런데 그냥 닫아 버리면 LOCK 6(조용한 실패 금지) 위반이다. 제외된 7행 중
-- 5행은 「읽지 못한 행」이고, 그건 **양식 해석이 틀렸다는 신호**다. 닫는 버튼이
-- 그 신호를 영영 지우면 배너가 있었던 이유가 사라진다.
--
-- ★ 그래서 «확인함»은 삭제가 아니라 **세고 있는 부재**다 ★
--
-- ADR-016의 `pending_cost.dismissed`가 같은 모양이다 — *「삭제가 아니라 세고 있는
-- 부재다. 화면이 «무시한 N건»을 셀 수 있고, 거둘 수 있다」*. 여기서도 배너는
-- 접히되 한 줄짜리 칩으로 남고, **사실이 바뀌면 다시 펴진다.**
--
-- ★ `seen_count`가 이 표의 요점이다 ★
--
-- 「확인함」은 «이 배너를 봤다»가 아니라 **«7행이라는 그 사실을 봤다»**이다.
-- 그래서 확인 당시의 수를 함께 저장한다. 새 파일을 넣어 제외가 12행이 되면
-- 그건 확인한 적 없는 새 소식이고 배너가 다시 펴진다. 수만 저장하고 「본 적
-- 있다」만 남기면, 문제가 커져도 화면이 조용해진다 — 가장 나쁜 실패다.
--
-- ★ 분류: 사람의 판단이다 (기준 계열) ★
--
-- Fact가 아니다 — 공통 6컬럼도 `row_shadow`도 없고 되돌리기 대상이 아니다.
-- `overhead_stance`(010)와 같은 등급이다: 행이 **없으면** 미확인이고, 그때만
-- 화면이 펼친다. 「확인 안 함」을 값으로 저장하지 않는다 (§22 — 부재는 boolean이
-- 아니고, 없는 것과 «아니라고 정한 것»은 다르다).
--
-- ★ 나중에 이 표가 받을 것 ★
--
-- 대기목록 3번(「진단 할 일 결정 기록 — 채택/기각 + 사유」)이 같은 모양이다.
-- `notice_key`를 열어 둔 이유가 그것이다 — 새 표를 또 만들지 않는다.
-- ═══════════════════════════════════════════════════════════════

CREATE TABLE notice_ack (
  library_id  TEXT NOT NULL REFERENCES library(id),

  -- 무엇을 확인했나. 화면이 정하는 안정된 문자열이다 (예: 'dash.excluded').
  -- 키에 숫자를 넣지 않는다 — 수가 바뀌면 «다른 알림»이 되어 확인이 무의미해진다.
  notice_key  TEXT NOT NULL,

  -- ★ 확인 당시의 수 ★ 지금 수가 이보다 크면 **확인한 적 없는 새 사실**이다.
  -- 작아지는 것(되돌리기로 제외가 준다)은 다시 물을 일이 아니라 그대로 접혀 있다.
  seen_count  INTEGER NOT NULL,

  acked_at    TEXT NOT NULL,

  PRIMARY KEY (library_id, notice_key)
) STRICT;

