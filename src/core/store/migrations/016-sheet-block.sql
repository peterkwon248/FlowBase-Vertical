-- ═══════════════════════════════════════════════════════════════
-- 016 — 통의 **깊은 층**: 파싱된 표를 보관한다
-- ═══════════════════════════════════════════════════════════════
--
-- [ADR-027](docs/ADR-027-원본-표-보관-형태.md) · [ADR-023](docs/ADR-023-통-묶음-자격-입구순서.md) 결정 1.
-- 015가 얕은 층(장부 + 무엇이 됐나)을 세웠고, 여기가 「아무 파일이나 표로 다시 본다」다.
--
-- ★ 형태는 **재서** 골랐다 — ADR-023의 재검토 트리거가 그걸 요구했다 ★
--
-- 픽스처 #13 `쿠팡 광고 보고서` (원본 10.05MB · 80,138행 × 43열 = 344만 셀),
-- 2026-08-21 · 이 기기 · 실제 SQLite에 넣고 파일 크기를 쟀다:
--
--     행당 JSON 평문      45.7MB   4.5배
--     행당 TSV 평문       43.0MB   4.3배
--     셀당 한 행          24.2바이트/셀 → 344만 셀이면 80MB 이상 · 344만 «행»
--     gzip 블록 2,000행    1.02MB   ★ 0.1배 — 42배 작다
--
-- 실 DB가 지금 34.1MB다. 평문이면 **광고 파일 하나로 두 배를 넘긴다.**
--
-- ★ 왜 JSONL인가 — 무손실에 5%를 낸다 ★
-- gzip TSV 1.02MB vs gzip JSONL 1.08MB. 그런데 TSV는 탭·개행이 든 셀을 망가뜨리고
-- `null`과 `""`, 숫자와 문자열을 뭉갠다. **오늘 픽스처에 그런 셀이 0개라 TSV를
-- 골라도 아무 시험이 안 깨진다** — 「우연히 안 터지는 중」이 정확히 그 모양이다.
-- 이 층의 존재 이유가 「원본 표를 다시 본다」인데 다시 본 표가 다르면 없느니만 못하다.
--
-- ★ SQL로 행 안을 못 뒤진다 — 그게 맞는 교환이다 ★
-- 결정된 쓰임은 「표로 다시 본다」= **페이지 단위 순차 읽기**이고 블록이 그걸 정확히
-- 서빙한다(한 블록 펼치기 13ms 실측). 「보관된 표에서 검색」이 필요해지면 그때 색인을
-- 따로 얹는다 — 지금 그걸 위해 42배를 내지 않는다.
--
-- ★ Fact가 아니라 메타다 ★ 009·015와 같다 — 공통 6컬럼(LOCK 1) 없고 `row_shadow`
-- 트리거도 안 붙는다. 되돌리기의 대상이 아니다.
--
-- 001을 고치지 않는다 (스키마 LOCK). 새 번호로 쌓는다.

-- 파싱된 표의 한 덩이. **2,000행이 한 블록**이다 (ADR-027 결정 2 — 실측).
CREATE TABLE sheet_block (
  sighting_id INTEGER NOT NULL REFERENCES file_sighting(id) ON DELETE CASCADE,
  -- 이 블록의 **첫 행 번호** (0-기준, 시트 안에서). 페이지 요청이 이 값으로 블록을 고른다.
  first_row   INTEGER NOT NULL,
  -- 이 블록이 든 행 수. 마지막 블록은 2,000보다 적다.
  row_count   INTEGER NOT NULL,
  -- gzip( JSON 배열을 개행으로 이은 것 )을 **base64로** 담는다.
  --
  -- 압축은 `CompressionStream` — `node:zlib`을 쓰면 ADR-011(실행 환경 중립)이 깨지고
  -- 웹판이 모듈 로드에서 죽는다.
  --
  -- ★ BLOB이 아닌 이유 (ADR-027 결정 7) ★ 드라이버 계약이
  -- `SqlValue = string | number | null`이라 BLOB을 넣으려면 구현 셋과 경계 시험을
  -- 함께 넓혀야 한다. 재보니 값어치가 없었다: gzip 1.08MB → base64 1.46MB (+33%)이고,
  -- 그래도 **평문 43.0MB의 1/29**이며 원본 xlsx(10.05MB)보다 작다.
  gz          TEXT NOT NULL,
  -- 같은 목격에 같은 시작 행이 두 블록이면 페이지가 두 번 그려진다.
  -- 재가져오기는 **갈아치우기**다 (015 `recordOutcomes`와 같은 판단).
  PRIMARY KEY (sighting_id, first_row)
) STRICT;

-- 「이 파일의 N행부터」 — 페이지 요청이 타는 길.
CREATE INDEX idx_sheet_block_range ON sheet_block(sighting_id, first_row);

