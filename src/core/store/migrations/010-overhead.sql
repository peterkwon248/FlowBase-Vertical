-- ═══════════════════════════════════════════════════════════════
-- 010 — 고정비·운영비: 손익 3층의 마지막 줄이 여기서 열린다
-- ═══════════════════════════════════════════════════════════════
--
-- ★ 원가보다 한 단계 더 빈 구멍이었다 (2026-08-19 실측) ★
--
--   원가    표 있음(cost_history) · 손입력 화면 있음 · 파일 문 없음  ← 8/19에 문을 냈다
--   고정비  표 없음 · 화면 배선 없음 · 문 없음                       ← 방 자체가 없었다
--
-- `snapshot.ts`가 `prorateFixed(base.fixedMonthly ?? 0, period)`를 부르는데
-- **`fixedMonthly`를 넣는 코드가 어디에도 없었다** (grep 2건 = 선언과 사용뿐).
-- 그래서 손익 3층의 마지막 줄이 구조적으로 항등식이었다:
--
--   채널 기여이익 − 고정비(늘 0) = 회사 순이익      → 두 줄이 늘 같은 수
--
-- 목업은 이 화면을 이미 그려 뒀다(`fixRows`·`opsRows`·`layerRows`). 시드가
-- 채우고 있었을 뿐이고, `src/app`에서 참조가 **0건**이었다.
--
-- ═══════════════════════════════════════════════════════════════
-- ★ 왜 고정비와 운영비가 **한 표**인가 ★
-- ═══════════════════════════════════════════════════════════════
--
-- 둘은 손익에서 완전히 다른 층에 들어간다:
--
--   운영비  주문·개수에 따라 나가는 돈 → **상품 기여이익**에서 뺀다 (배분한다)
--   고정비  얼마를 팔든 나가는 돈       → **회사 순이익**에서만 뺀다 (배분 안 한다)
--
-- 그런데 **가장 흔한 실수가 «이건 어느 쪽이지?»**다. 3PL 피킹 수수료는 개당이라
-- 운영비지만 월 정액 계약이면 고정비다. 창고 보관료도 마찬가지다. 표를 둘로
-- 쪼개면 잘못 넣은 항목을 옮기려고 **지우고 다시 넣어야** 하고, 그러면 적용일
-- 이력이 끊긴다 — 「3월부터 임대료 인상」이 사라진다.
--
-- 한 표면 `kind`만 바꾸면 옮겨진다. 이력이 그대로 따라간다.
--
-- ═══════════════════════════════════════════════════════════════
-- ★ 적용일이 있어야 하는 이유 — ADR-005 개정의 근거 ★
-- ═══════════════════════════════════════════════════════════════
--
-- ADR-005는 «v1 이력 = 원가만»이라고 명시적으로 축소했다. 그 근거는
-- **«과거를 다시 계산하기 위해 필요한 이력만 시계열로 둔다»**였고, 고정비는
-- 정확히 그 조건을 만족한다:
--
--   3월에 임대료가 180만 → 220만으로 올랐다
--   → 2월 손익은 **180만으로 계산돼야 한다.** 오늘 값으로 지난달이 바뀌면 틀린 숫자다
--
-- 원가와 같은 성질이므로 같은 모양(대상 + 종류 + 금액 + 적용 시작일 + 입력자)을
-- 쓴다. ADR-005가 «다른 기준 데이터에 이력이 필요해지면 같은 모양의 테이블을
-- 추가하면 된다»고 재검토 경로를 열어 뒀고, 이게 그 첫 사례다.
--
-- ★ 지우기가 없다 ★
-- 사무실을 뺐으면 「임대료 삭제」가 아니라 **금액 0원을 6월 1일부터**다.
-- 그래야 5월 손익에 임대료가 남고 6월부터 사라진다. 행을 지우면 과거가 바뀐다.
--
-- ═══════════════════════════════════════════════════════════════
-- ★ `overhead_stance` — 「안 넣음」도 입력이다 (§22) ★
-- ═══════════════════════════════════════════════════════════════
--
-- 「고정비 0원」에는 두 가지 뜻이 있는데 지금 `gaps.ts`는 구분하지 못한다:
--
--   ① 아직 안 넣었다        → 앱이 물어봐야 한다
--   ② 일부러 안 넣는다      → 앱이 «0이 맞다»고 알아야 한다
--      (원가에 이미 포함 · 1인 사업자라 임대료가 없음 · 아직 사무실이 없음)
--
-- 판정 조건이 `pnl.fixed === 0` 하나뿐이라 ②인 사용자에게 **영영** 「미입력」이라고
-- 잔소리한다. 진단 화면에 지워지지 않는 줄이 하나 박히면 사용자는 그 화면 전체를
-- 안 보게 되고, **경고 하나가 죽으면 옆의 진짜 경고도 같이 죽는다.**
--
-- 그래서 「두지 않는다」를 선언으로 받는다. 행이 **없는 것**이 «미선언»이고,
-- 그 셋이 화면에서 다른 문장이 된다.
--
-- ★ 이 선언은 이력이 아니다 ★
-- 「원가에 포함이다」는 상태이지 시계열이 아니다. 지난달의 stance로 지난달을
-- 다시 계산할 일이 없다 — 계산에 안 들어가고 **문장만 고른다.** 그래서 PK가
-- `(library_id, kind)` 하나이고 덮어쓴다 (ADR-005의 «나머지는 updated_at만»).

CREATE TABLE overhead (
  id             INTEGER PRIMARY KEY AUTOINCREMENT,
  library_id     TEXT NOT NULL REFERENCES library(id),

  -- 어느 층에서 빠지는가. 옮기려면 이 값만 바꾼다 (위 «한 표인 이유»).
  kind           TEXT NOT NULL CHECK (kind IN ('FIXED','OPS')),

  -- 무엇에 비례하는가. `FIXED`는 `MONTH`만 쓴다 — 「얼마를 팔든」이 정의라
  -- 주문·개수에 비례하면 그건 고정비가 아니라 운영비다.
  --   MONTH  월 정액 (기간은 일할 안분 — `prorateFixed`)
  --   ORDER  주문 1건당
  --   UNIT   품목 1개당
  basis          TEXT NOT NULL CHECK (basis IN ('MONTH','ORDER','UNIT')),

  -- 사람이 붙인 이름. 「임대료」·「인건비」. 이게 곧 대상이라 UNIQUE에 들어간다.
  label          TEXT NOT NULL,

  amount         INTEGER NOT NULL,       -- 원 단위 정수. 부동소수 금지 (001과 같은 규율)
  effective_from TEXT NOT NULL,          -- 적용 시작일 (YYYY-MM-DD)
  note           TEXT,
  entered_at     TEXT NOT NULL,
  entered_by     TEXT NOT NULL CHECK (entered_by IN ('user','import')),

  -- 같은 항목의 같은 적용일은 하나다. 값을 고치면 UPSERT로 덮고, 「3월부터
  -- 올랐다」는 **새 적용일의 새 행**이다 — `cost_history`와 같은 규약.
  UNIQUE (library_id, kind, label, effective_from)
) STRICT;

-- 조회는 늘 «이 기간에 유효한 값»이다: kind로 좁히고 effective_from으로 뒤에서 센다.
CREATE INDEX idx_overhead_lookup ON overhead(library_id, kind, effective_from);

CREATE TABLE overhead_stance (
  library_id  TEXT NOT NULL REFERENCES library(id),
  kind        TEXT NOT NULL CHECK (kind IN ('FIXED','OPS')),

  --   none   두지 않는다 — 화면이 «0이 맞다»고 말하고 더 묻지 않는다
  --   later  나중에 넣겠다 — 조용히 기다린다. 재촉하지 않는다
  -- 행이 **없으면** 미선언이고, 그때만 앱이 묻는다.
  stance      TEXT NOT NULL CHECK (stance IN ('none','later')),

  -- 왜 두지 않는가. `in-cogs`가 특히 중요하다 — 이걸 선언한 사용자가 나중에
  -- 고정비를 넣으려 하면 화면이 **이중 차감**을 경고할 수 있다.
  --   in-cogs         원가에 이미 포함돼 있다
  --   not-applicable  해당 없음 (임대료 없는 1인 사업자 등)
  --   (그 밖)          사람이 적은 문장
  reason      TEXT,
  declared_at TEXT NOT NULL,
  PRIMARY KEY (library_id, kind)
) STRICT;

