-- ═══════════════════════════════════════════════════════════════
-- 004 — 리스팅의 입도(grain)를 **선언**으로 남긴다
-- ═══════════════════════════════════════════════════════════════
--
-- `listing_key`는 "파일이 주는 가장 가는 판매 단위"로 만든다. 그런데 그 단위가
-- 채널마다 다르다:
--
--   ESM 주문통합검색   상품번호만 있다            → 리스팅 = 상품 단위
--   11번가 정산확정    상품번호 + 옵션명이 있다   → 리스팅 = 옵션 단위
--
-- 결과적으로 **같은 실물 상품이 ESM에선 리스팅 1개, 11번가에선 옵션 수만큼 N개**가
-- 된다. 연결 화면에서 이는 "11번가 옵션 3개 → SKU 1개 · ESM 상품 1개 → 같은 SKU"라는
-- N:1 연결로 나타난다. **그건 결함이 아니라 이 비대칭의 정상 표현이다.**
--
-- 비대칭을 코드가 추론하게 두면(“11번가면 옵션이겠거니”) 그 추론은 마켓 지식이 되어
-- core로 새고, 새 채널이 올 때마다 틀린다. 그래서 **행마다 선언한다** —
-- 리스팅을 만든 프로파일이 자기 입도를 적어 넣는다.
--
--   'product'  상품 단위 (옵션 구분 없음)
--   'option'   옵션 단위 (같은 상품의 옵션이 각자 한 행)
--
-- 001을 고치지 않는다 (스키마 LOCK). 새 번호로 쌓는다.

ALTER TABLE marketplace_listing ADD COLUMN grain TEXT;

-- 앞으로 들어오는 행은 반드시 채운다. 기존 행이 없으므로(리스팅 적재 자체가
-- 이번에 처음이다) 백필은 필요 없다.
--
-- ★ CHECK 제약을 걸지 않는 이유 ★
-- SQLite의 ALTER TABLE ADD COLUMN은 CHECK를 붙일 수 없다. 값 검증은 적재 경로
-- (`Repository.upsertListings`)가 타입으로 강제한다 — 거기가 유일한 입구다.

-- 그림자 트리거는 손대지 않는다. `row_shadow`는 **Fact 되돌리기**의 장치이고
-- 리스팅은 batch에 묶이지 않아 되돌리기의 대상이 아니다 (ADR-012).

