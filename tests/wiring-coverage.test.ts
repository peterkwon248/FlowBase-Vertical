/**
 * 배선 커버리지 게이트 — **«이식했다»와 «작동한다»를 가른다.**
 *
 * ─────────────────────────────────────────────────────────────
 * ★ 이 게이트가 없어서 생긴 일 (2026-08-17) ★
 *
 * 사용자가 «목업 대비 허접하다»고 했다. 세어 보니 마크업이 읽는데 **채우는 코드가
 * 0곳**인 블록이 다섯이었다 — 일별 차트 · 상품별 손익 · 채널별 손익 · 무버스 ·
 * 확인 팝오버. 그런데 그때 게이트는 **전부 초록**이었다:
 *
 * ```
 * convert-gate   마크업이 목업과 같은가       ← 초록 (마크업은 100% 이식됐다)
 * (없음)         그 자리에 값이 들어오는가     ← 아무도 안 재고 있었다
 * ```
 *
 * 그래서 문서에는 「화면 6개 배선」이라고 적혀 있는데 화면은 비어 있었고, 그 차이를
 * **사람 눈이** 발견했다. 발견 경로가 사람 눈이면 매번 놀라게 된다.
 * ─────────────────────────────────────────────────────────────
 *
 * ★ 게이트는 «100%»를 요구하지 않는다 ★
 * 안 만들기로 한 것(컷 목록·헌장이 금지한 것)이 대부분이라 100%는 틀린 목표다.
 * 지키는 것은 **«늘어나지 않는다»** 하나다 — 마크업이 새 자리를 만들었는데 아무도
 * 안 채우면 그때 빨개진다. 그리고 그 수는 **줄어들기만 한다**(래칫).
 */

import { describe, expect, it } from "vitest"
import { wiringReport } from "../tools/harness/wiring.js"

/**
 * ★ 남은 일의 상한 — **줄어들기만 한다** ★
 *
 * 배선을 하나 붙이면 이 수를 함께 내린다. 못 내리면 그 커밋은 배선을 한 것이
 * 아니다. 올리는 것은 **마크업이 새 자리를 만들었을 때만** 정당하고, 그때는
 * 왜 안 채웠는지가 `CUTS`에 선언되거나 여기 이유가 적혀야 한다.
 *
 * 2026-08-17 기준 9 = 부분 데이터 고지 3 + 정산 조정 6.
 * 2026-08-18 기준 6 = 정산 조정 6. **부분 데이터 고지 3이 배선됐다** —
 * `partial` 배너가 `batch_exclusion`을 읽어 「파일에서 N행이 제외됐습니다」를 말한다.
 */
const TODO_MAX = 6

describe("배선 커버리지 — 마크업이 쓰는 자리에 값이 들어오는가", () => {
  const r = wiringReport()

  it("★ 선언되지 않은 미배선이 늘어나지 않는다 ★", () => {
    const list = r.screens
      .filter((s) => s.todo.length > 0)
      .map((s) => `${s.screen}: ${s.todo.join(" · ")}`)
      .join("\n")
    expect(r.allTodo.length, `남은 일이 늘었다 — 새 자리를 만들었으면 채우거나 선언한다\n${list}`)
      .toBeLessThanOrEqual(TODO_MAX)
  })

  it("상한이 낡지 않았다 — 다 채웠으면 상한도 내린다", () => {
    // 실제보다 상한이 3 넘게 높으면 그 수는 이미 사실이 아니다.
    expect(TODO_MAX - r.allTodo.length, "배선을 붙였으면 TODO_MAX도 함께 내린다").toBeLessThan(3)
  })

  it("세는 대상이 실재한다 — 소비도 배선도 0이면 시험이 헛돈다", () => {
    expect(r.allConsumed.length).toBeGreaterThan(100)
    expect(r.allWired.length).toBeGreaterThan(50)
  })

  /**
   * 선언이 낡으면(그 필드가 마크업에서 사라지면) 목록이 조용히 썩는다.
   * `DEVIATIONS`가 «선언이 낡으면 실패한다»로 지키는 것과 같은 규율이다.
   */
  it("아무것도 안 덮는 선언이 없다 — 목록이 썩지 않는다", () => {
    const dead = Object.entries(r.cutHits)
      .filter(([, n]) => n === 0)
      .map(([name]) => name)
    expect(dead, `이 선언은 이제 아무 필드도 안 덮는다 — 지워야 한다: ${dead.join(", ")}`).toEqual([])
  })

  it("★ 헌장이 금지한 자리는 **배선되지 않은 채로** 있어야 한다 ★", () => {
    // LOCK 10 — 「동기화」 카피. 채우는 순간 화면이 금지어를 말한다.
    for (const f of ["syncLine", "syncColor"]) {
      expect(r.allWired, `${f}이 배선됐다 — LOCK 10 위반이다`).not.toContain(f)
    }
  })
})
